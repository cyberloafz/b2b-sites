import { json, one, q } from "@/db/client";
import type { Site } from "@/schema/site";

/**
 * Legal pages (privacy, terms, accessibility) are generated from templates and start with a
 * "sample text" notice. Publishing is blocked while the notice is there; an owner confirms the
 * pages were reviewed, which removes the notice and records who confirmed and when.
 */
export const SAMPLE_NOTICE = /^\*Sample (?:text|policy) generated by the platform\.[^\n]*\*[ \t]*\n*/m;
export const SAMPLE_NOTICE_TEXT = "*Sample text generated by the platform. Have it reviewed by your counsel before relying on it.*\n\n";

export function unreviewedLegalPages(site: Pick<Site, "pages">) {
  return site.pages.filter((p) => p.template === "legal" && p.sections.some((b) => b.type === "rich_text" && SAMPLE_NOTICE.test(b.body)));
}

export type LegalReview = { by: string; at: string; pages: string[] };

export async function confirmLegalPages(siteId: string, by: string): Promise<{ ok: true; pages: string[] }> {
  const rows = await q<{ id: number; slug: string; data: { type: string; body?: string } }>(
    `SELECT s.id, p.slug, s.data FROM sections s JOIN pages p ON p.id = s.page_id
      WHERE p.site_id = $1 AND p.template = 'legal' AND s.type = 'rich_text'`, [siteId]);
  const changed: string[] = [];
  for (const r of rows) {
    if (!r.data.body || !SAMPLE_NOTICE.test(r.data.body)) continue;
    await q("UPDATE sections SET data = $1 WHERE id = $2", [json({ ...r.data, body: r.data.body.replace(SAMPLE_NOTICE, "").trimStart() }), r.id]);
    changed.push(r.slug);
  }
  const cur = await one<{ settings: Record<string, unknown> }>("SELECT settings FROM sites WHERE id = $1", [siteId]);
  const review: LegalReview = { by, at: new Date().toISOString(), pages: [...new Set(changed)] };
  await q("UPDATE sites SET settings = $1, updated_at = now() WHERE id = $2", [json({ ...(cur?.settings ?? {}), legalReview: review }), siteId]);
  return { ok: true, pages: review.pages };
}
