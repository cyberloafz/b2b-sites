import { SiteSchema, type Site } from "./site";
import { checkThemeContrast } from "./theme";
import { H1_CAPABLE } from "./blocks";
// Kept in sync with lib/legal.ts (schema/ stays free of database code).
const SAMPLE_LEGAL = /^\*Sample (?:text|policy) generated by the platform\.[^\n]*\*/m;

export type Issue = { level: "error" | "warning"; where: string; message: string };

const words = (s: string) => s.trim().split(/\s+/).filter(Boolean).length;

/**
 * Full validation the platform runs before preview and before publish:
 * 1. Shape (zod schema)  2. Cross-references  3. SEO / content rules  4. Accessibility tokens.
 * Errors block publishing; warnings show in the SEO report.
 */
export function validateSite(input: unknown): { site?: Site; issues: Issue[] } {
  const parsed = SiteSchema.safeParse(input);
  if (!parsed.success) {
    return {
      issues: parsed.error.issues.map((i) => ({ level: "error", where: i.path.join("."), message: i.message })),
    };
  }
  const site = parsed.data;
  const issues: Issue[] = [];
  const err = (where: string, message: string) => issues.push({ level: "error", where, message });
  const warn = (where: string, message: string) => issues.push({ level: "warning", where, message });

  // --- accessibility tokens
  for (const m of checkThemeContrast(site.theme)) err("theme", m);

  // --- uniqueness
  const dup = <T>(arr: T[], key: (t: T) => string, label: string) => {
    const seen = new Set<string>();
    for (const t of arr) {
      const k = key(t);
      if (seen.has(k)) err(label, `Duplicate: ${k}`);
      seen.add(k);
    }
  };
  dup(site.pages, (p) => p.slug, "pages");
  dup(site.collections, (c) => c.slug, "collections");
  dup(site.products, (p) => p.slug, "products");

  // --- references
  const colSlugs = new Set(site.collections.map((c) => c.slug));
  const prodSlugs = new Set(site.products.map((p) => p.slug));
  const svcSlugs = new Set(site.services.map((s) => s.slug));
  for (const c of site.collections) if (!svcSlugs.has(c.service)) err(`collections.${c.slug}`, `Unknown service "${c.service}"`);
  for (const p of site.products) if (!colSlugs.has(p.collection)) err(`products.${p.slug}`, `Unknown collection "${p.collection}"`);

  const allSections = site.pages.flatMap((p) => p.sections.map((s) => ({ where: `pages[${p.slug}].${s.id}`, s })));
  for (const p of site.pages) dup(p.sections, (s) => s.id, `pages[${p.slug}] section ids`);
  for (const { where, s } of allSections) {
    if (s.type === "category_tiles") for (const c of s.categories) if (!colSlugs.has(c)) err(where, `Unknown collection "${c}"`);
    if (s.type === "product_grid") {
      if (s.source.kind === "collection" && !colSlugs.has(s.source.collection)) err(where, `Unknown collection "${s.source.collection}"`);
      if (s.source.kind === "manual") for (const p of s.source.products) if (!prodSlugs.has(p)) err(where, `Unknown product "${p}"`);
    }
    if (["announcement_bar", "header", "footer"].includes(s.type)) err(where, `${s.type} belongs in globals, not on a page`);
  }

  // --- one H1 per page: every page needs at least one block able to carry it
  for (const p of site.pages) {
    if (!p.sections.some((s) => H1_CAPABLE.includes(s.type))) err(`pages[${p.slug}]`, "No block can carry the page H1");
  }

  // --- unfinished placeholders block publishing; each is reported where it lives
  const todosIn = (v: unknown) => JSON.stringify(v).match(/\[\[TODO:[^\]]*\]\]/g) ?? [];
  const reportTodos = (where: string, v: unknown) => {
    for (const t of new Set(todosIn(v))) err(where, `Replace the placeholder ${t}`);
  };
  for (const p of site.pages) for (const b of p.sections) reportTodos(`pages[${p.slug}].${b.id}`, b);
  for (const [k, b] of Object.entries(site.globals)) reportTodos(`globals.${k}`, b);
  for (const c of site.collections) reportTodos(`collections.${c.slug}`, c);
  for (const p of site.products) reportTodos(`products.${p.slug}`, p);
  reportTodos("company", site.company);

  // --- template legal text must be reviewed by the company before it goes live
  for (const p of site.pages)
    if (p.template === "legal")
      for (const b of p.sections)
        if (b.type === "rich_text" && SAMPLE_LEGAL.test(b.body))
          err(`pages[${p.slug}].${b.id}`, "This is sample legal text. Have it reviewed, then confirm it under “Legal pages” on the Publish page");

  // --- thin-content rule for long-tail category pages
  for (const c of site.collections) {
    const n = site.products.filter((p) => p.collection === c.slug).length;
    if (n < 3) warn(`collections.${c.slug}`, `Only ${n} products — page will be noindex until it has 3`);
    if (words(c.intro) < 120) warn(`collections.${c.slug}`, `Intro is ${words(c.intro)} words — page will be noindex until it has 120`);
  }

  // --- near-duplicate category intros (word 5-gram overlap)
  const grams = (s: string) => {
    const w = s.toLowerCase().replace(/[^a-z0-9 ]/g, " ").split(/\s+/).filter(Boolean);
    const g = new Set<string>();
    for (let i = 0; i + 5 <= w.length; i++) g.add(w.slice(i, i + 5).join(" "));
    return g;
  };
  const cg = site.collections.map((c) => ({ slug: c.slug, g: grams(c.intro) }));
  for (let i = 0; i < cg.length; i++)
    for (let j = i + 1; j < cg.length; j++) {
      const a = cg[i].g, b = cg[j].g;
      const inter = [...a].filter((x) => b.has(x)).length;
      const sim = inter / Math.max(1, Math.min(a.size, b.size));
      if (sim > 0.3) warn(`collections.${cg[i].slug}`, `Intro overlaps ${Math.round(sim * 100)}% with ${cg[j].slug} — rewrite one`);
    }

  return { site, issues };
}
